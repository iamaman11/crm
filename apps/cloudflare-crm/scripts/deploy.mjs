import { existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
const required = n => { if(!process.env[n]) throw Error("Missing "+n); return process.env[n]; };
const sha=required("GITHUB_SHA");
if(!/^[0-9a-f]{40}$/.test(sha) || process.env.GITHUB_REF!=="refs/heads/feature/cloudflare-native-crm-20261107" || process.env.GITHUB_EVENT_NAME!=="push") throw Error("Untrusted deployment");
const account="5bd5e1e1e813f061afc259e91334262d",database="35fc7ee9-9710-485f-8fb3-f5a398b229b4";
if(required("CLOUDFLARE_ACCOUNT_ID")!==account || required("CRM_D1_DATABASE_ID")!==database) throw Error("Wrong Cloudflare CRM target");
const token=required("CLOUDFLARE_API_TOKEN");
function cmd(...args){const r=spawnSync("npx",args,{cwd:"apps/cloudflare-crm",stdio:"inherit"});if(r.status!==0)throw Error("Failed npx "+args[0]);}
if(!existsSync("apps/cloudflare-crm/rust-party/build/index.js")) throw Error("Native Rust Party Worker not built");
cmd("vite","build");
cmd("wrangler","d1","migrations","apply","crm-dev","--remote");
cmd("wrangler","deploy","--var","GIT_SHA:"+sha);
const h={Authorization:"Bearer "+token}, api="https://api.cloudflare.com/client/v4/accounts/"+account;
const r=await fetch(api+"/workers/scripts/crm-dev/settings",{headers:h}).then(x=>x.json());
const b=r.result?.bindings||[];
if(!r.success||b.find(x=>x.name==="GIT_SHA")?.text!==sha||b.find(x=>x.name==="DB")?.id!==database)throw Error("Deployment readback mismatch");
const url="https://crm-dev.crm-5bd5e1e1.workers.dev";
const anonymous=await fetch(url+"/api/health",{redirect:"manual"});
if(anonymous.status===200||anonymous.status>=500)throw Error("Access not protecting CRM");
const authorized=await fetch(url+"/api/health",{redirect:"manual",headers:{"CF-Access-Client-Id":required("CRM_E2E_A_CLIENT_ID"),"CF-Access-Client-Secret":required("CRM_E2E_A_CLIENT_SECRET")}});
if(authorized.status!==200)throw Error("Authenticated CRM health failed");
console.log(JSON.stringify({event:"crm.deploy",sha,account,database,result:"deployed",browserE2E:"NOT_TESTED"}));
