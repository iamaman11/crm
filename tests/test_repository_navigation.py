    def test_repository_workflow_and_parser_contracts_remain_intact(self) -> None:
        affected = (ROOT / ".github/workflows/affected-scope.yml").read_text(
            encoding="utf-8"
        )
        self.assertIn("Validate active repository packet", affected)
        self.assertIn('python scripts/repo.py packet-check --base "${BASE_REF}"', affected)
        generated_sync = (ROOT / ".github/workflows/rust-generated-sync.yml").read_text(
            encoding="utf-8"
        )
        rust_ci = (ROOT / ".github/workflows/rust.yml").read_text(encoding="utf-8")
        for workflow in (generated_sync, rust_ci):
            self.assertNotIn("cargo generate-lockfile", workflow)
            self.assertIn("cargo metadata --locked --format-version 1 --no-deps", workflow)
            self.assertIn("git diff --exit-code -- Cargo.lock", workflow)
        owner_execution = (
            ROOT / ".github/workflows/customer-privacy-owner-execution.yml"
        ).read_text(encoding="utf-8")
        self.assertGreaterEqual(
            owner_execution.count("customer_privacy_owner_execution_ready_postgres"),
            6,
        )
        self.assertIn("Verify clean PostgreSQL ready-work acceptance", owner_execution)
        self.assertIn(
            "Repeat PostgreSQL ready-work acceptance after reapply", owner_execution
        )
        background = (ROOT / "crates/crm-application-runtime/src/background.rs").read_text(
            encoding="utf-8"
        )
        for marker in (
            "CUSTOMER_PRIVACY_OWNER_EXECUTION_WORKER_ID",
            "BackgroundWorkerPhase::new(260)",
            "CustomerPrivacyProductionDependencies",
            "privacy_dependencies.try_into()",
        ):
            self.assertIn(marker, background)
        contract_ci = (ROOT / ".github/workflows/contracts.yml").read_text(
            encoding="utf-8"
        )
        for marker in (
            "tests/test_contract_lifecycle.py",
            "tests/test_contract_lifecycle_preproduction.py",
            "tests/test_contract_lifecycle_transitions.py",
            "tests/test_contract_release_evidence.py",
            "tests/test_contract_retirement_evidence.py",
            "tests/test_contract_telemetry_catalog.py",
            "scripts/contract_lifecycle_preproduction.py",
            "scripts/contract_lifecycle_transitions.py",
            "scripts/contract_release_evidence.py",
            "scripts/contract_retirement_evidence.py",
            "scripts/generate_contract_lifecycle.py",
            "scripts/generate_contract_telemetry_catalog.py",
            "/releases?per_page=100",
            "/tags?per_page=100",
            "/deployments?per_page=100",
            '--base-ref "origin/${BASE_REF}"',
        ):
            self.assertIn(marker, contract_ci)
        governance = (ROOT / ".github/workflows/governance.yml").read_text(
            encoding="utf-8"
        )
        self.assertGreaterEqual(governance.count('"scripts/local_lifecycle.py"'), 2)
        self.assertGreaterEqual(governance.count('"scripts/local_demo.py"'), 2)
        self.assertGreaterEqual(governance.count('"tests/test_local_demo.py"'), 2)
        self.assertGreaterEqual(governance.count('"tests/test_local_lifecycle.py"'), 2)
        self.assertIn("python scripts/repo.py conformance", governance)
        self.assertIn("Run deterministic local demo seed replay and smoke acceptance", governance)
        parser = build_parser()
        explain = parser.parse_args(
            ["explain", "customer_privacy.legal_hold.place@1.0.0", "--json"]
        )
        self.assertEqual(explain.command, "explain")
        packet = parser.parse_args(
            ["packet-check", "--base", "origin/main", "--write-generated"]
        )
        self.assertEqual(packet.command, "packet-check")
        self.assertTrue(packet.write_generated)
        doctor = parser.parse_args(["doctor", "--profile", "bootstrap", "--json"])
        self.assertEqual(doctor.command, "doctor")
        self.assertEqual(doctor.profile, "bootstrap")
        bootstrap = parser.parse_args(["bootstrap", "--dry-run", "--json"])
        self.assertEqual(bootstrap.command, "bootstrap")
        self.assertTrue(bootstrap.dry_run)


