from __future__ import annotations

from pathlib import Path
import unittest
from unittest.mock import patch

from scripts.repository_navigation import (
    ACTIVE_PACKET_PATH,
    NAVIGATION_SCHEMA,
    REPOSITORY_MAP_PATH,
    NavigationError,
    evaluate_path_policy,
    explain_target,
    generated_documents,
    load_packet,
    packet_check,
    stale_generated_documents,
)
from scripts.repo import build_parser

ROOT = Path(__file__).resolve().parents[1]


class RepositoryNavigationTests(unittest.TestCase):

    def test_active_step_21_evidence_sync_packet_declaration_is_exact(self) -> None:
        packet = load_packet(ROOT)
        self.assertEqual(packet["schema_version"], "crm.repository-packet/v1")
        self.assertEqual(packet["packet_id"], "repository-step-21-evidence-sync")
        self.assertEqual(packet["status"], "active")
        self.assertEqual(
            packet["baseline"],
            {"ref": "main", "sha": "c21894f47f24e81da1cc150f9ea457fcfdc2bd63"},
        )
        self.assertEqual(packet["tracking_issues"], [194, 126, 28])
        self.assertTrue(
            {
                "docs/ARCHITECTURE_COMPLEXITY_AND_SCALABILITY_PLAN.md",
                "docs/IMPLEMENTATION_ROADMAP.md",
                "docs/MODULE_CATALOG.md",
                "docs/PHASE8_DELIVERY_PLAN.md",
                "docs/PRODUCT_DEVELOPMENT_10_OF_10_PLAN.md",
                "docs/PROJECT_STATUS.md",
                "tests/test_architecture_documentation_consistency.py",
                "tests/test_repository_navigation.py",
            }.issubset(set(packet["allowed_paths"]))
        )
        self.assertIn("PR #296", " ".join(packet["deliverables"]))
        self.assertIn("Repository Step 22", " ".join(packet["deliverables"]))

    def test_generated_navigation_is_deterministic_and_current(self) -> None:
        first = generated_documents(ROOT)
        second = generated_documents(ROOT)
        self.assertEqual(first, second)
        self.assertEqual(set(first), {ACTIVE_PACKET_PATH, REPOSITORY_MAP_PATH})
        for content in first.values():
            self.assertIn(
                "Generated by scripts/generate_repository_navigation.py", content
            )
            self.assertRegex(content, r"source-digest: sha256:[0-9a-f]{64}")
        self.assertIn(
            "repository-step-21-evidence-sync", first[ACTIVE_PACKET_PATH],
        )
        self.assertIn(
            "c21894f47f24e81da1cc150f9ea457fcfdc2bd63", first[ACTIVE_PACKET_PATH]
        )
        self.assertIn("**Workspace packages:** 112", first[REPOSITORY_MAP_PATH])
        self.assertIn("`crm.customer-privacy`", first[REPOSITORY_MAP_PATH])
        self.assertEqual(stale_generated_documents(ROOT), [])

    def test_module_and_capability_explanations_remain_resolvable(self) -> None:
        module = explain_target(ROOT, "crm.customer-privacy")
        self.assertEqual(module["schema_version"], NAVIGATION_SCHEMA)
        self.assertEqual(module["kind"], "module")
        self.assertEqual(module["version"], "0.3.0")
        coordinates = {
            capability["coordinate"] for capability in module["capabilities"]
        }
        self.assertIn("customer_privacy.case.submit@1.0.0", coordinates)
        self.assertIn("customer_privacy.restriction.place@1.0.0", coordinates)
        capability = explain_target(ROOT, "customer_privacy.case.submit@1.0.0")
        self.assertEqual(capability["kind"], "capability")
        self.assertEqual(capability["route"]["classification"], "public_runtime")
        with self.assertRaisesRegex(NavigationError, "unknown module or capability"):
            explain_target(ROOT, "customer_privacy.unknown@1.0.0")

    def test_path_policy_rejects_forbidden_and_unscoped_changes(self) -> None:
        forbidden, disallowed = evaluate_path_policy(
            [
                "docs/PROJECT_STATUS.md",
                "proto/crm/customer/v1/customer.proto",
                "unowned.txt",
            ],
            ["docs/PROJECT_STATUS.md"],
            ["proto/**"],
        )
        self.assertEqual(forbidden, ["proto/crm/customer/v1/customer.proto"])
        self.assertEqual(disallowed, ["unowned.txt"])

    def test_packet_check_uses_exact_planning_baseline(self) -> None:
        packet = load_packet(ROOT)
        workflow_paths = {
            "Affected Scope CI": ".github/workflows/affected-scope.yml",
            "Complexity Baseline CI": ".github/workflows/complexity-baseline.yml",
            "Customer Privacy Access Export CI": ".github/workflows/customer-privacy-access-export.yml",
            "Customer Privacy Operations CI": ".github/workflows/customer-privacy-operations.yml",
            "Customer Privacy Owner Execution CI": ".github/workflows/customer-privacy-owner-execution.yml",
            "Customer Privacy Hold Retention CI": ".github/workflows/customer-privacy-hold-retention.yml",
            "Customer Privacy Restriction Policy CI": ".github/workflows/customer-privacy-restriction-policy.yml",
            "Governance CI": ".github/workflows/governance.yml",
            "Rust Generated Sync": ".github/workflows/rust-generated-sync.yml",
            "Rust CI": ".github/workflows/rust.yml",
        }
        affected = {
            "head_sha": "b" * 40,
            "changed_paths": packet["allowed_paths"],
            "affected_packages": [],
            "selected_workflows": [
                {
                    "name": name,
                    "path": workflow_paths[name],
                    "selected": True,
                    "reasons": ["Step 21 accepted evidence synchronization"],
                }
                for name in packet["required_checks"]
            ],
        }
        with (
            patch(
                "scripts.repository_navigation._git",
                return_value="c21894f47f24e81da1cc150f9ea457fcfdc2bd63",
            ),
            patch("scripts.repository_navigation.build_report", return_value=affected),
            patch(
                "scripts.repository_navigation.stale_generated_documents",
                return_value=[],
            ),
        ):
            report = packet_check(ROOT, "origin/main")
        self.assertTrue(report["ok"])
        self.assertEqual(report["changed_paths"], packet["allowed_paths"])
        self.assertEqual(report["blockers"], [])

    def test_repository_workflow_and_parser_contracts_remain_intact(self) -> None:
        affected = (ROOT / ".github/workflows/affected-scope.yml").read_text(
            encoding="utf-8"
        )
        self.assertIn("Validate active repository packet", affected)
        self.assertIn(
            'python scripts/repo.py packet-check --base "${BASE_REF}"', affected
        )
        generated_sync = (ROOT / ".github/workflows/rust-generated-sync.yml").read_text(
            encoding="utf-8"
        )
        rust_ci = (ROOT / ".github/workflows/rust.yml").read_text(encoding="utf-8")
        for workflow in (generated_sync, rust_ci):
            self.assertNotIn("cargo generate-lockfile", workflow)
            self.assertIn(
                "cargo metadata --locked --format-version 1 --no-deps", workflow
            )
            self.assertIn("git diff --exit-code -- Cargo.lock", workflow)
        owner_execution = (
            ROOT / ".github/workflows/customer-privacy-owner-execution.yml"
        ).read_text(encoding="utf-8")
        self.assertGreaterEqual(
            owner_execution.count("customer_privacy_owner_execution_ready_postgres"),
            6,
        )
        self.assertIn("Verify clean PostgreSQL ready-work acceptance", owner_execution)
        self.assertIn(
            "Repeat PostgreSQL ready-work acceptance after reapply", owner_execution
        )
        background = (
            ROOT / "crates/crm-application-runtime/src/background.rs"
        ).read_text(encoding="utf-8")
        for marker in (
            "CUSTOMER_PRIVACY_OWNER_EXECUTION_WORKER_ID",
            "BackgroundWorkerPhase::new(260)",
            "CustomerPrivacyProductionDependencies",
            "privacy_dependencies.try_into()",
        ):
            self.assertIn(marker, background)
        contract_ci = (ROOT / ".github/workflows/contracts.yml").read_text(
            encoding="utf-8"
        )
        for marker in (
            "tests/test_contract_lifecycle.py",
            "tests/test_contract_lifecycle_preproduction.py",
            "tests/test_contract_lifecycle_transitions.py",
            "tests/test_contract_release_evidence.py",
            "tests/test_contract_retirement_evidence.py",
            "tests/test_contract_telemetry_catalog.py",
            "scripts/contract_lifecycle_preproduction.py",
            "scripts/contract_lifecycle_transitions.py",
            "scripts/contract_release_evidence.py",
            "scripts/contract_retirement_evidence.py",
            "scripts/generate_contract_lifecycle.py",
            "scripts/generate_contract_telemetry_catalog.py",
            "/releases?per_page=100",
            "/tags?per_page=100",
            "/deployments?per_page=100",
            '--base-ref "origin/${BASE_REF}"',
        ):
            self.assertIn(marker, contract_ci)
        governance = (ROOT / ".github/workflows/governance.yml").read_text(
            encoding="utf-8"
        )
        self.assertGreaterEqual(governance.count('"scripts/local_lifecycle.py"'), 2)
        self.assertGreaterEqual(governance.count('"scripts/local_demo.py"'), 2)
        self.assertGreaterEqual(governance.count('"tests/test_local_demo.py"'), 2)
        self.assertGreaterEqual(governance.count('"tests/test_local_lifecycle.py"'), 2)
        self.assertIn("python scripts/repo.py conformance", governance)
        self.assertIn(
            "Run deterministic local demo seed replay and smoke acceptance", governance
        )
        parser = build_parser()
        explain = parser.parse_args(
            ["explain", "customer_privacy.legal_hold.place@1.0.0", "--json"]
        )
        self.assertEqual(explain.command, "explain")
        packet = parser.parse_args(
            ["packet-check", "--base", "origin/main", "--write-generated"]
        )
        self.assertEqual(packet.command, "packet-check")
        self.assertTrue(packet.write_generated)
        doctor = parser.parse_args(["doctor", "--profile", "bootstrap", "--json"])
        self.assertEqual(doctor.command, "doctor")
        self.assertEqual(doctor.profile, "bootstrap")
        bootstrap = parser.parse_args(["bootstrap", "--dry-run", "--json"])
        self.assertEqual(bootstrap.command, "bootstrap")
        self.assertTrue(bootstrap.dry_run)


if __name__ == "__main__":
    unittest.main()
