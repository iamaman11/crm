from __future__ import annotations

from pathlib import Path
import unittest
from unittest.mock import patch

from scripts.repository_navigation import (
    ACTIVE_PACKET_PATH,
    NAVIGATION_SCHEMA,
    REPOSITORY_MAP_PATH,
    NavigationError,
    evaluate_path_policy,
    explain_target,
    generated_documents,
    load_packet,
    packet_check,
    stale_generated_documents,
)
from scripts.repo import build_parser


ROOT = Path(__file__).resolve().parents[1]


class RepositoryNavigationTests(unittest.TestCase):
    def test_active_packet_declaration_is_exact(self) -> None:
        packet = load_packet(ROOT)
        self.assertEqual(packet["schema_version"], "crm.repository-packet/v1")
        self.assertEqual(packet["packet_id"], "repository-step-18-seed-demo-smoke")
        self.assertEqual(packet["status"], "active")
        self.assertEqual(
            packet["baseline"],
            {"ref": "main", "sha": "953b9f929f8e89c351c59ebc01461fffab3689ff"},
        )
        self.assertEqual(packet["tracking_issues"], [194])
        self.assertEqual(set(packet["allowed_paths"]), {'tests/test_architecture_documentation_consistency.py', 'services/crm-api/tests/local_demo_smoke_e2e.rs', 'AGENTS.md', 'tests/test_repository_navigation.py', 'tests/test_local_demo.py', 'affected-scope-policy.json', 'repository-packet.json', 'docs/DEVELOPMENT_WORKFLOW.md', 'scripts/local_demo.py', 'scripts/repo.py', 'docs/ACTIVE_PACKET.md', 'README.md', '.github/workflows/governance.yml'})
        self.assertEqual(packet["required_checks"], ['Affected Scope CI', 'Application Runtime CI', 'Complexity Baseline CI', 'Customer Privacy Access Export CI', 'Customer Privacy Approval CI', 'Customer Privacy Owner Execution CI', 'Customer Privacy Persistence CI', 'Customer Privacy Restriction Policy CI', 'Data Quality Process Runtime CI', 'Database CI', 'Export Process Runtime CI', 'Generic Mutation Query Conformance CI', 'Governance CI', 'Import Process Runtime CI', 'Import Retryable Process Runtime CI', 'PostgreSQL Process Isolation Pilot', 'Product Plane CI', 'Rust Generated Sync', 'Rust CI'])
        self.assertIn(
            "run clean reset, seed, exact replay and smoke as permanent Governance acceptance",
            packet["deliverables"],
        )
        self.assertIn(
            "mark Repository Step 18 complete or start Repository Step 19",
            packet["non_goals"],
        )

    def test_generated_navigation_is_deterministic_and_current(self) -> None:
        first = generated_documents(ROOT)
        second = generated_documents(ROOT)
        self.assertEqual(first, second)
        self.assertEqual(set(first), {ACTIVE_PACKET_PATH, REPOSITORY_MAP_PATH})
        for content in first.values():
            self.assertIn("Generated by scripts/generate_repository_navigation.py", content)
            self.assertRegex(content, r"source-digest: sha256:[0-9a-f]{64}")
        self.assertIn(
            "repository-step-18-seed-demo-smoke",
            first[ACTIVE_PACKET_PATH],
        )
        self.assertIn(
            "953b9f929f8e89c351c59ebc01461fffab3689ff",
            first[ACTIVE_PACKET_PATH],
        )
        self.assertIn("**Workspace packages:** 112", first[REPOSITORY_MAP_PATH])
        self.assertIn("`crm.customer-privacy`", first[REPOSITORY_MAP_PATH])
        self.assertEqual(stale_generated_documents(ROOT), [])

    def test_module_and_capability_explanations_remain_resolvable(self) -> None:
        module = explain_target(ROOT, "crm.customer-privacy")
        self.assertEqual(module["schema_version"], NAVIGATION_SCHEMA)
        self.assertEqual(module["kind"], "module")
        self.assertEqual(module["version"], "0.3.0")
        coordinates = {capability["coordinate"] for capability in module["capabilities"]}
        self.assertIn("customer_privacy.case.submit@1.0.0", coordinates)
        self.assertIn("customer_privacy.restriction.place@1.0.0", coordinates)
        capability = explain_target(ROOT, "customer_privacy.case.submit@1.0.0")
        self.assertEqual(capability["kind"], "capability")
        self.assertEqual(capability["route"]["classification"], "public_runtime")
        with self.assertRaisesRegex(NavigationError, "unknown module or capability"):
            explain_target(ROOT, "customer_privacy.unknown@1.0.0")

    def test_path_policy_rejects_forbidden_and_unscoped_changes(self) -> None:
        forbidden, disallowed = evaluate_path_policy(
            ["docs/PROJECT_STATUS.md", "proto/crm/customer/v1/customer.proto", "unowned.txt"],
            ["docs/PROJECT_STATUS.md"],
            ["proto/**"],
        )
        self.assertEqual(forbidden, ["proto/crm/customer/v1/customer.proto"])
        self.assertEqual(disallowed, ["unowned.txt"])

