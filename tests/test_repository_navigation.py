from __future__ import annotations

from pathlib import Path
import unittest
from unittest.mock import patch

from scripts.repository_navigation import (
    ACTIVE_PACKET_PATH,
    NAVIGATION_SCHEMA,
    REPOSITORY_MAP_PATH,
    NavigationError,
    evaluate_path_policy,
    explain_target,
    generated_documents,
    load_packet,
    packet_check,
    stale_generated_documents,
)
from scripts.repo import build_parser


ROOT = Path(__file__).resolve().parents[1]


class RepositoryNavigationTests(unittest.TestCase):
    def test_active_packet_declaration_is_exact(self) -> None:
        packet = load_packet(ROOT)
        self.assertEqual(packet["schema_version"], "crm.repository-packet/v1")
        self.assertEqual(
            packet["packet_id"], "repository-step-16-worker-conformance-adoption"
        )
        self.assertEqual(packet["status"], "active")
        self.assertEqual(
            packet["baseline"],
            {"ref": "main", "sha": "0f38247d24a709afec9136b7a7ef44230837ebd0"},
        )
        self.assertEqual(packet["tracking_issues"], [126, 194])
        self.assertEqual(
            set(packet["allowed_paths"]),
            {
                "crates/crm-application-runtime/tests/postgres_customer_enrichment_application_worker.rs",
                "crates/crm-customer-enrichment-application-composition/tests/postgres_application_worker_process.rs",
                "docs/ACTIVE_PACKET.md",
                "repository-packet.json",
                "services/crm-api/tests/import_process_retryable_e2e.rs",
                "services/crm-api/tests/support/generic_worker_conformance.rs",
                "tests/test_generic_conformance_adoption.py",
                "tests/test_repository_navigation.py",
            },
        )
        self.assertEqual(
            packet["required_checks"],
            [
                "Affected Scope CI",
                "Application Runtime CI",
                "Complexity Baseline CI",
                "Customer Enrichment Review Process Runtime CI",
                "Generic Mutation Query Conformance CI",
                "Import Retryable Process Runtime CI",
                "Rust Generated Sync",
                "Rust CI",
            ],
        )
        self.assertIn(
            "add one std-only business-neutral WorkerConformanceSuite with reusable no-side-effect, retryable-progress and exact-recovery assertions",
            packet["deliverables"],
        )
        self.assertIn(
            "declare Repository Step 16 complete, Phase 8A complete, Architecture 10/10 or any product-complete expert module",
            packet["non_goals"],
        )

    def test_generated_navigation_is_deterministic_and_current(self) -> None:
        first = generated_documents(ROOT)
        second = generated_documents(ROOT)
        self.assertEqual(first, second)
        self.assertEqual(set(first), {ACTIVE_PACKET_PATH, REPOSITORY_MAP_PATH})
        for content in first.values():
            self.assertIn("Generated by scripts/generate_repository_navigation.py", content)
            self.assertRegex(content, r"source-digest: sha256:[0-9a-f]{64}")
        self.assertIn(
            "repository-step-16-worker-conformance-adoption", first[ACTIVE_PACKET_PATH]
        )
        self.assertIn(
            "0f38247d24a709afec9136b7a7ef44230837ebd0", first[ACTIVE_PACKET_PATH]
        )
        self.assertIn("**Workspace packages:** 112", first[REPOSITORY_MAP_PATH])
        self.assertIn("`crm.customer-privacy`", first[REPOSITORY_MAP_PATH])
        self.assertEqual(stale_generated_documents(ROOT), [])

    def test_module_and_capability_explanations_remain_resolvable(self) -> None:
        module = explain_target(ROOT, "crm.customer-privacy")
        self.assertEqual(module["schema_version"], NAVIGATION_SCHEMA)
        self.assertEqual(module["kind"], "module")
        self.assertEqual(module["version"], "0.3.0")
        coordinates = {capability["coordinate"] for capability in module["capabilities"]}
        self.assertIn("customer_privacy.case.submit@1.0.0", coordinates)
        self.assertIn("customer_privacy.restriction.place@1.0.0", coordinates)
        capability = explain_target(ROOT, "customer_privacy.case.submit@1.0.0")
        self.assertEqual(capability["kind"], "capability")
        self.assertEqual(capability["route"]["classification"], "public_runtime")
        with self.assertRaisesRegex(NavigationError, "unknown module or capability"):
            explain_target(ROOT, "customer_privacy.unknown@1.0.0")

    def test_path_policy_rejects_forbidden_and_unscoped_changes(self) -> None:
        forbidden, disallowed = evaluate_path_policy(
            ["docs/PROJECT_STATUS.md", "proto/crm/customer/v1/customer.proto", "unowned.txt"],
            ["docs/PROJECT_STATUS.md"],
            ["proto/**"],
        )
        self.assertEqual(forbidden, ["proto/crm/customer/v1/customer.proto"])
        self.assertEqual(disallowed, ["unowned.txt"])

    def test_packet_check_uses_exact_planning_baseline(self) -> None:
        packet = load_packet(ROOT)
        workflow_paths = {
            "Affected Scope CI": ".github/workflows/affected-scope.yml",
            "Application Runtime CI": ".github/workflows/application-runtime.yml",
            "Complexity Baseline CI": ".github/workflows/complexity-baseline.yml",
            "Customer Enrichment Review Process Runtime CI": ".github/workflows/customer-enrichment-review-process-runtime.yml",
            "Generic Mutation Query Conformance CI": ".github/workflows/generic-conformance.yml",
            "Import Retryable Process Runtime CI": ".github/workflows/import-retryable-process-runtime.yml",
            "Rust Generated Sync": ".github/workflows/rust-generated-sync.yml",
            "Rust CI": ".github/workflows/rust.yml",
        }
        affected = {
            "head_sha": "b" * 40,
            "changed_paths": packet["allowed_paths"],
            "affected_packages": [
                "crm-api",
                "crm-application-runtime",
                "crm-customer-enrichment-application-composition",
            ],
            "selected_workflows": [
                {
                    "name": name,
                    "path": workflow_paths[name],
                    "selected": True,
                    "reasons": ["Step 16 worker conformance adoption"],
                }
                for name in packet["required_checks"]
            ],
        }
        with (
            patch(
                "scripts.repository_navigation._git",
                return_value="0f38247d24a709afec9136b7a7ef44230837ebd0",
            ),
            patch("scripts.repository_navigation.build_report", return_value=affected),
            patch("scripts.repository_navigation.stale_generated_documents", return_value=[]),
        ):
            report = packet_check(ROOT, "origin/main")
        self.assertTrue(report["ok"])
        self.assertEqual(report["changed_paths"], packet["allowed_paths"])
        self.assertEqual(report["blockers"], [])

    def test_repository_workflow_and_parser_contracts_remain_intact(self) -> None:
        affected = (ROOT / ".github/workflows/affected-scope.yml").read_text(encoding="utf-8")
        self.assertIn("Validate active repository packet", affected)
        self.assertIn('python scripts/repo.py packet-check --base "${BASE_REF}"', affected)
        generated_sync = (ROOT / ".github/workflows/rust-generated-sync.yml").read_text(encoding="utf-8")
        rust_ci = (ROOT / ".github/workflows/rust.yml").read_text(encoding="utf-8")
        for workflow in (generated_sync, rust_ci):
            self.assertNotIn("cargo generate-lockfile", workflow)
            self.assertIn("cargo metadata --locked --format-version 1 --no-deps", workflow)
            self.assertIn("git diff --exit-code -- Cargo.lock", workflow)
        parser = build_parser()
        explain = parser.parse_args(["explain", "customer_privacy.legal_hold.place@1.0.0", "--json"])
        self.assertEqual(explain.command, "explain")
        packet = parser.parse_args(["packet-check", "--base", "origin/main", "--write-generated"])
        self.assertEqual(packet.command, "packet-check")
        self.assertTrue(packet.write_generated)


if __name__ == "__main__":
    unittest.main()
